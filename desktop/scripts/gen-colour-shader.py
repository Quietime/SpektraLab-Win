#!/usr/bin/env python3
"""Transliterate the original Mac CAM16 body; keep its equations unchanged."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[2]
source = (root / 'modern_UI/Spektrafilm/Spektrafilm/Canvas/Shaders.metal').read_text()
start = source.index('static inline float3 cam16ucsInto(')
body = source[source.index('{', start) + 1:source.index('\nkernel void outputTransform', start)].strip()
assert body.endswith('}')
body = body[:-1]
body = re.sub(r'const uint nL = .*?;', 'int nL = oRows, nh = oCols; bool lc_active = oLightness;', body, count=1)
for a, b in [('u.cam16K', 'oK'), ('u.cam16M2X', 'oM2X'), ('u.cam16M2R', 'oM2R'),
             ('float3', 'vec3'), ('fabs(', 'abs('), ('atan2(', 'atan('), ('lc_active != 0u', 'lc_active')]:
    body = body.replace(a, b)
body = re.sub(r'\bconst\s+', '', body)
body = re.sub(r'(?<=\d)[fu]\b', '', body)
body = body.replace('(int)floor(Li)', 'int(floor(Li))').replace('(float)(nL - 1)', 'float(nL - 1)')
body = re.sub(r'\((int|float)\)([A-Za-z_]\w*)', r'\1(\2)', body)
body = re.sub(r'cmax\[([^\]]+)\]', r'cmaxAt(\1)', body)
body = body.replace('moved =', 'bool moved =').replace('outside =', 'bool outside =')
header = '''// Generated by scripts/gen-colour-shader.py from Canvas/Shaders.metal.
// Keep the original equations; constants and C_max come from the live engine.
export const OUTPUT_COLOUR_GLSL = `
uniform float oMatrix[9];
uniform float oM2X[9];
uniform float oM2R[9];
uniform float oK[22];
uniform int oRows;
uniform int oCols;
uniform bool oActive;
uniform bool oLightness;
uniform bool oIdentity;
uniform sampler2D oCmax;
float cmaxAt(int i) { return texelFetch(oCmax, ivec2(i % oCols, i / oCols), 0).r; }
vec3 cam16Into(vec3 rgb) {
'''
footer = '''
}
float outputEncode(float v) { return v <= .0031308 ? 12.92*v : 1.055*pow(max(v,0.),1./2.4)-.055; }
vec3 outputColour(vec3 c) {
  if(oIdentity) return c;
  vec3 v = mix(c / 16., pow(max(c,0.), vec3(1.8)), greaterThanEqual(c,vec3(16./512.)));
  vec3 lin = vec3(dot(vec3(oMatrix[0],oMatrix[1],oMatrix[2]),v),
                  dot(vec3(oMatrix[3],oMatrix[4],oMatrix[5]),v),
                  dot(vec3(oMatrix[6],oMatrix[7],oMatrix[8]),v));
  if(oActive) lin=cam16Into(lin);
  return vec3(outputEncode(lin.r),outputEncode(lin.g),outputEncode(lin.b));
}
`;
'''
(root/'desktop/src/canvas/colourShader.ts').write_text(header + body + footer)
